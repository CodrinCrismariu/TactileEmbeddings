"""Verify cached codes using the encoder batches that generated them.

The original production cache builder uses batches of 128 plus the final
episode remainder. On CUDA, a three-frame re-encoding can select a different
convolution kernel even with float32 inputs and outputs. Verify the original
execution contract at the same tight tolerance, not a relaxed comparison.

Kept separate from the pinned teacher/cache builder so completed checkpoints
retain their original implementation provenance.
"""
from pathlib import Path

import numpy as np
import torch

from .aligned_frames import file_hash, write_json
from .bimanual_mirror import require_spec, transform_targets


def verification_chunks(frames, batch_size=128):
    if frames<1 or batch_size<1:raise ValueError('Positive episode length and encoder batch size required')
    selected=np.unique([0,frames//2,frames-1])
    return [np.arange(start,min(start+batch_size,frames),dtype=np.int64)
            for start in sorted({int(i)//batch_size*batch_size for i in selected})]


def verify_codes(rows,index,policy,device,chunk_frames=128):
    from . import mirror_preparation as preparation
    source=index['signature']['source'];spec=require_spec(policy,source)
    # v1 production CLI has always used this builder/default batch contract.
    # Do not silently bless data generated by a different implementation.
    pinned=index['signature']['implementation']['mirror_preparation.py']
    if file_hash(preparation.__file__)!=pinned:
        raise ValueError('Cannot reproduce a different mirror cache encoder implementation')
    model,_=preparation.load_model(index['teacher'],device)
    lookup={r['episode_id']:r for r in index['episodes']};reader=preparation.NativeTargets();checks=[]
    for split in ('train','val'):
        row=next(r for r in rows if r['split']==split);record=lookup[row['episode_id']]
        if file_hash(record['path'])!=record['sha256']:raise ValueError('Corrupt paired code artifact')
        with np.load(record['path'],allow_pickle=False) as archive,torch.inference_mode():
            np.testing.assert_array_equal(archive['frame_indices'],np.arange(row['frames']))
            for indices in verification_chunks(row['frames'],chunk_frames):
                original=reader.read(row,indices)
                for variant,value in enumerate([original,transform_targets(original,spec)]):
                    with torch.autocast(torch.device(device).type,enabled=False):
                        fresh,valid=preparation.encode(model,preparation.to_device(value,device))
                    fresh=fresh.float().cpu().numpy();saved=archive['codes'][variant,indices]
                    np.testing.assert_allclose(saved,fresh,rtol=2e-5,atol=2e-5)
                    np.testing.assert_array_equal(archive['valid'][variant,indices],valid.cpu().numpy())
                    checks.append(dict(episode_id=row['episode_id'],split=split,variant=variant,
                        first_frame=int(indices[0]),last_frame=int(indices[-1]),batch_frames=len(indices),
                        max_absolute_error=float(np.max(np.abs(saved-fresh)))))
    folder=Path(index['episodes'][0]['path']).parent
    result=dict(passed=True,index_sha256=file_hash(folder/'index.json'),episodes=checks,
        verification_contract='original-encoder-batches-v1',encoder_batch_frames=chunk_frames,
        tolerance=dict(rtol=2e-5,atol=2e-5),verifier_sha256=file_hash(__file__),
        torch_version=torch.__version__,device_type=torch.device(device).type,
        cudnn_allow_tf32=torch.backends.cudnn.allow_tf32,
        matmul_allow_tf32=torch.backends.cuda.matmul.allow_tf32,
        max_absolute_error=max(check['max_absolute_error'] for check in checks))
    write_json(folder/'verification.json',result)
    return result


def install():
    """Use the corrected verifier without rewriting pinned builder provenance."""
    from . import mirror_preparation
    mirror_preparation.verify_codes=verify_codes
